#!/usr/bin/env python3
"""Export real reference data for the owner app in owner_app/ (standard library only, deterministic).

Writes two files in owner_app/src/lib/connect/:
reference.generated.ts (shipped to the browser):
  - HOLIDAY_NAMES: English day name -> name in fi / sv / nb / en, from data/calendar_special_days.csv
    (fi from FI rows, sv from SE rows, nb from NO rows) plus the event / school-break phrases of build_bundles.py;
  - REASONS: one short reason per basis and language (build_bundles.REASON, the same words as the Telegram text);
demo.generated.ts (server only):
  - DEMO: the bundles and items of samples/bundles_demo.json (used only when the app runs without Supabase).

    python3 result/B_contact_decide/export_frontend_data.py
"""
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import build_bundles as bb  # noqa: E402  (REASON, SPECIAL_NAMES, LANGS)

OUT_DIR = os.path.join(HERE, "owner_app", "src", "lib", "connect")
COUNTRY_LANG = {"FI": "fi", "SE": "sv", "NO": "nb"}


def holiday_names():
    names = {}
    with open(os.path.join(ROOT, "data", "calendar_special_days.csv"), encoding="utf-8") as f:
        for r in csv.DictReader(f):
            lang = COUNTRY_LANG.get(r["country"])
            if not lang:
                continue
            entry = names.setdefault(r["name_en"], {"en": r["name_en"]})
            entry.setdefault(lang, r["name_local"])
    # day names used by explain_full() for rows that are not in the calendar
    names["an event night nearby"] = bb.SPECIAL_NAMES["EVENT"]
    names["a school-break day"] = bb.SPECIAL_NAMES["SCHOOL_BREAK"]
    return {k: names[k] for k in sorted(names)}


def demo():
    with open(os.path.join(HERE, "samples", "bundles_demo.json"), encoding="utf-8") as f:
        return json.load(f)


def write(name, consts):
    lines = ["// Generated by result/B_contact_decide/export_frontend_data.py. Do not edit by hand.", ""]
    for const, value in consts.items():
        lines.append(f"export const {const} = {json.dumps(value, ensure_ascii=False, indent=1, sort_keys=True)} as const;")
        lines.append("")
    path = os.path.join(OUT_DIR, name)
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return os.path.relpath(path, ROOT)


def main():
    names = holiday_names()
    d = demo()
    print("wrote", write("reference.generated.ts", {"HOLIDAY_NAMES": names, "REASONS": {l: bb.REASON[l] for l in bb.LANGS}}),
          f"({len(names)} holiday names)")
    print("wrote", write("demo.generated.ts", {"DEMO": d}), f"({len(d['bundles'])} demo bundles, {len(d['bundle_items'])} items)")


if __name__ == "__main__":
    main()
