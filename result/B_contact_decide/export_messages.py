#!/usr/bin/env python3
"""Write MESSAGES.md: the exact customer messages the system sends, as text (standard library only, deterministic).

Sources, read only:
  - samples/bundles_demo.json         first messages (bundles.intro_text, built by build_bundles.py)
  - ../n8n/Connect · Reply.json       every follow-up text and button label (the DICT in the Render node)
  - ../n8n/Connect · Scheduler.json   the reminder line (Reminder Payload node)

    python3 result/B_contact_decide/export_messages.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
N8N = os.path.join(os.path.dirname(HERE), "n8n")
OUT = os.path.join(HERE, "MESSAGES.md")
LANGS = ("fi", "sv", "nb", "en")
LANG_NAME = {"fi": "Finnish", "sv": "Swedish", "nb": "Norwegian", "en": "English"}
# One first message per (route, language) we can show from the 17 demo businesses (first match in bundle order).
WANTED = [("SUGGEST", "fi"), ("ASK", "fi"), ("AUTO_APPLY", "fi"), ("SUGGEST", "sv"), ("ASK", "sv"),
          ("SUGGEST", "nb"), ("ASK", "nb"), ("STAFF", "en")]
FOLLOW_UPS = [  # (key, when it is sent)
    ("msg_applied", "after the owner approves (or confirms an edit) and the Yext write is verified; followed by one line per channel with its update time"),
    ("msg_auto_applied", "standing permission: hours were applied without asking; the owner can undo"),
    ("msg_edit_prompt", "after the owner taps Edit"),
    ("msg_confirm_title", "the owner's free-text edit was understood; a confirm card lists the changes"),
    ("msg_clarify", "the free-text edit could not be understood"),
    ("msg_bad_time", "closing time before opening time"),
    ("msg_bad_date", "the date is not in this suggestion"),
    ("msg_declined", "after the owner taps No thanks"),
    ("msg_undone", "after Undo"),
    ("msg_cancelled", "after Cancel on the confirm card"),
    ("msg_permission_offer", "after the first approval, if the owner has no standing permission"),
    ("msg_permission_granted", "after the owner grants standing permission"),
    ("msg_apply_failed", "the Yext write could not be verified; staff are told as well"),
    ("msg_already_handled", "a button on a suggestion that is already handled"),
    ("msg_help", "any other message to the bot"),
]
BUTTONS = ["btn_approve", "btn_edit", "btn_decline", "btn_closed", "btn_regular", "btn_confirm", "btn_cancel",
           "btn_undo", "btn_permission_yes", "btn_not_now", "btn_retry"]


def node_code(workflow, name):
    with open(os.path.join(N8N, workflow), encoding="utf-8") as f:
        w = json.load(f)
    return next(n for n in w["nodes"] if n["name"] == name)["parameters"]["jsCode"]


def reply_dict():
    code = node_code("Connect · Reply.json", "Render")
    start = code.index("const DICT = ") + len("const DICT = ")
    end = code.index("\n};", start) + 2
    return json.loads(code[start:end])


def reminder_prefix():
    code = node_code("Connect · Scheduler.json", "Reminder Payload")
    out = {}
    for lang, a, b in re.findall(r'(fi|sv|nb|en): "(.*?)" \+ label \+ "(.*?)",', code):
        out[lang] = f"{a}<reply-by date>{b}"
    return out


def fence(text):
    return "```text\n" + text.strip() + "\n```"


def main():
    with open(os.path.join(HERE, "samples", "bundles_demo.json"), encoding="utf-8") as f:
        demo = json.load(f)
    d = reply_dict()
    remind = reminder_prefix()
    L = ["# Customer messages (as text)", "",
         "Generated by `export_messages.py` from the texts the system actually sends: first messages from",
         "`samples/bundles_demo.json` (`bundles.intro_text`, built by `build_bundles.py` from fixed templates, no LLM), follow-ups",
         "and button labels from the n8n workflow `Connect · Reply` (node `Render`), the reminder line from `Connect · Scheduler`.",
         "Telegram renders the buttons under each message. Finnish, Swedish and Norwegian were written by the team's agent and",
         "still need a native-speaker check.", "",
         "## 1. First message (one per bundle)", "",
         "Route `SUGGEST` proposes hours (buttons Approve / Edit / No thanks); `ASK` asks when we are not sure (Closed / Open as",
         "usual / Edit); `AUTO_APPLY` is the follow-up text kept for an owner with standing permission; `STAFF` is an internal",
         "English note to Fonecta staff (a business that looks closed for good is never messaged).", ""]
    for route, lang in WANTED:
        b = next((x for x in demo["bundles"] if x["route"] == route and x["language"] == lang), None)
        if not b:
            continue
        btn = {"SUGGEST": ["btn_approve", "btn_edit", "btn_decline"], "ASK": ["btn_closed", "btn_regular", "btn_edit"]}.get(route)
        L.append(f"### {route} · {LANG_NAME[lang]} · {b['business_name']} ({b['entity_id']})")
        L.append("")
        L.append(fence(b["intro_text"]))
        if btn:
            L.append("Buttons: " + " · ".join(f"`{d[k][lang]}`" for k in btn))
        L.append("")
    L += ["## 2. Reminder (once, if there is no answer)", "",
          "Sent by `Connect · Scheduler` 4 days after the first message, at the latest 2 days before the deadline; the first",
          "message follows it unchanged, with the same buttons.", "",
          "| Language | Text |", "|---|---|"]
    L += [f"| {lang} | {remind[lang]} |" for lang in LANGS if lang in remind]
    L += ["", "## 3. Follow-ups (approve / edit / decline / undo / permission)", ""]
    for key, when in FOLLOW_UPS:
        L.append(f"**`{key}`**: {when}.")
        L.append("")
        L.append("| Language | Text |")
        L.append("|---|---|")
        L += [f"| {lang} | {d[key][lang]} |" for lang in LANGS if lang in d.get(key, {})]
        L.append("")
    L += ["## 4. Button labels", "", "| Key | fi | sv | nb | en |", "|---|---|---|---|---|"]
    L += [f"| `{k}` | " + " | ".join(d[k][x] for x in LANGS) + " |" for k in BUTTONS if k in d]
    L += ["", "## 5. Staff messages (English, internal)", ""]
    L += [f"- `{k}`: {d[k]['en']}" for k in ("msg_staff_flag", "msg_staff_error") if k in d]
    L += ["", "## 6. The owner app (no login)", "",
          "The web app shows the same suggestion as one card per date, with the holiday name in the owner's language, the hours",
          "shown now and the suggested hours, the confidence in words and the reason. Its texts are in",
          "`owner_app/src/lib/i18n.ts` (fi / sv / nb / en).", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print(f"wrote {os.path.relpath(OUT, os.path.dirname(os.path.dirname(HERE)))}")


if __name__ == "__main__":
    main()
